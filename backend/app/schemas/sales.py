"""Point-of-sale, sales history and customer return schemas."""

import re
import uuid
from datetime import datetime
from decimal import Decimal
from typing import Annotated, Literal

from pydantic import BaseModel, Field, field_validator, model_validator

from app.schemas.common import ORMModel
from app.schemas.stock import UserBrief

Qty = Annotated[Decimal, Field(gt=0, le=Decimal("99999.999"), decimal_places=3)]
MoneyIn = Annotated[Decimal, Field(ge=0, le=Decimal("99999999.99"), decimal_places=2)]
Method = Literal["CASH", "MPESA", "CARD"]

MPESA_RE = re.compile(r"^[A-Z0-9]{10}$")
PHONE_RE = re.compile(r"^\+?[0-9 ]{7,20}$")


class CartLine(BaseModel):
    product_id: int
    quantity: Qty
    discount: MoneyIn = Decimal("0")  # KES off this line


class CheckoutRequest(BaseModel):
    client_request_id: uuid.UUID = Field(
        ..., description="Random id generated by the till; resubmitting it returns the same sale"
    )
    items: list[CartLine] = Field(..., min_length=1, max_length=200)
    cart_discount: MoneyIn = Decimal("0")
    payment_method: Method
    amount_tendered: MoneyIn | None = None
    payment_reference: str | None = Field(None, max_length=40)
    customer_name: str | None = Field(None, max_length=150)
    customer_phone: str | None = Field(None, max_length=30)
    notes: str | None = Field(None, max_length=500)

    @field_validator("payment_reference")
    @classmethod
    def _ref(cls, v: str | None) -> str | None:
        v = (v or "").strip().upper()
        return v or None

    @field_validator("customer_phone")
    @classmethod
    def _phone(cls, v: str | None) -> str | None:
        v = (v or "").strip()
        if not v:
            return None
        if not PHONE_RE.match(v):
            raise ValueError("must be a phone number such as 0712345678")
        return v

    @model_validator(mode="after")
    def _payment(self) -> "CheckoutRequest":
        if self.payment_method == "CASH" and self.amount_tendered is None:
            raise ValueError("Enter the cash received")
        if self.payment_method == "MPESA":
            if not self.payment_reference or not MPESA_RE.match(self.payment_reference):
                raise ValueError("Enter the 10-character M-Pesa transaction code, e.g. SKD4H2L9QX")
        return self


